/**
 * Chromium PDF renderer.
 *
 * Template rendering pipeline:
 *   1. Read HTML/Handlebars template from templateDir (LRU cached)
 *   2. Compile and execute template with job payload data
 *   3. Load rendered HTML into a fresh Puppeteer page via setContent()
 *   4. page.pdf() with A4, printBackground: true
 *   5. Close the page (NOT the browser — reuse via BrowserPool)
 *
 * Request interception design:
 *   We allow document, stylesheet, and font requests through (needed for
 *   rendering). All other types (image, xhr, fetch, script) are aborted.
 *   JavaScript is disabled — all data is baked into the HTML by Handlebars.
 */
import * as fs from 'fs/promises';
import * as path from 'path';
import Handlebars from 'handlebars';
import { Browser } from 'puppeteer-core';
import { Logger } from 'winston';

export interface RenderResult {
  pdfBytes: Buffer;
  elapsedMs: number;
}

// Resource types to allow through when request interception is active.
const ALLOWED_RESOURCE_TYPES = new Set(['document', 'stylesheet', 'font']);

export class ChromiumRenderer {
  private readonly templateCache = new Map<string, HandlebarsTemplateDelegate>();

  constructor(
    private readonly templateDir: string,
    private readonly log: Logger,
  ) {}

  async render(
    browser: Browser,
    templateName: string,
    data: unknown,
  ): Promise<RenderResult> {
    const start = Date.now();

    const tmpl = await this.getTemplate(templateName);
    const html  = tmpl(data);

    const page = await browser.newPage();
    try {
      // Disable JS — Handlebars has already expanded all data server-side.
      await page.setJavaScriptEnabled(false);

      // Intercept requests: allow only document/stylesheet/font; abort the rest.
      // IMPORTANT: the handler must call continue() or abort() on EVERY request,
      // otherwise the page load hangs indefinitely.
      await page.setRequestInterception(true);
      page.on('request', (req) => {
        if (ALLOWED_RESOURCE_TYPES.has(req.resourceType())) {
          req.continue();
        } else {
          req.abort();
        }
      });

      await page.setContent(html, { waitUntil: 'domcontentloaded', timeout: 15_000 });

      const pdf = await page.pdf({
        format:               'A4',
        printBackground:      true,
        margin: { top: '20mm', bottom: '25mm', left: '20mm', right: '15mm' },
        displayHeaderFooter:  true,
        headerTemplate: `
          <div style="font-size:8px;color:#888;width:100%;text-align:right;padding:0 20mm;">
            Page <span class="pageNumber"></span> of <span class="totalPages"></span>
          </div>`,
        footerTemplate: `
          <div style="font-size:8px;color:#888;width:100%;text-align:center;">
            Generated by DocEngine &middot; Digitally Signed
          </div>`,
      });

      const elapsedMs = Date.now() - start;
      this.log.debug('chromium render complete', {
        templateName,
        elapsedMs,
        bytes: pdf.length,
      });

      return { pdfBytes: Buffer.from(pdf), elapsedMs };
    } finally {
      // Always close the page — never close the browser (BrowserPool manages it)
      await page.close().catch(() => { /* best effort */ });
    }
  }

  private async getTemplate(name: string): Promise<HandlebarsTemplateDelegate> {
    const cached = this.templateCache.get(name);
    if (cached) return cached;

    const filePath = path.join(this.templateDir, `${name}.html`);
    const source   = await fs.readFile(filePath, 'utf-8');
    const compiled = Handlebars.compile(source, { strict: true });
    this.templateCache.set(name, compiled);
    return compiled;
  }
}
